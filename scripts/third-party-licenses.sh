#!/usr/bin/env bash
# Writes THIRD-PARTY-LICENSES.md: the license texts of everything compiled
# into the wamux-http binary (the Go standard library and every module the
# command links) and of the files the panel embeds. The tarball and both
# images ship it; scripts/ci.sh fails when it is stale.
#
# usage: scripts/third-party-licenses.sh [output]   (default: THIRD-PARTY-LICENSES.md)
set -euo pipefail
cd "$(dirname "$0")/.."
out=${1:-THIRD-PARTY-LICENSES.md}

# The toolchain the release builds with, as go.mod pins it.
toolchain=$(awk '$1 == "toolchain" { print $2 }' go.mod)
[ -n "$toolchain" ] || toolchain=go$(awk '$1 == "go" { print $2 }' go.mod)

# A module path in the proxy's escaped form (an upper-case letter becomes
# "!" and the letter in lower case).
escape() { sed -E 's/([A-Z])/!\L\1/g' <<<"$1"; }

# Every license-like file at the root of a directory, in a stable order.
license_files() {
  find "$1" -maxdepth 1 -type f \
    \( -iname 'licen[cs]e*' -o -iname 'copying*' -o -iname 'notice*' -o -iname 'patents*' \) \
    | LC_ALL=C sort
}

fence() {
  printf '\n`%s`\n\n````text\n' "$1"
  cat "$2"
  printf '\n````\n'
}

{
  cat <<'EOF'
# Third-party licenses

The `wamux-http` binary is built from this repository's code (MIT OR
Apache-2.0) and the code below, which it links statically. This file is
generated by `scripts/third-party-licenses.sh`; do not edit it by hand.

Each module's source is at the address given, the exact version the binary
was built with.
EOF

  printf '\n## Go standard library (%s)\n\nSource: https://go.dev/dl/%s.src.tar.gz\n' "$toolchain" "$toolchain"
  goroot=$(go env GOROOT)
  for f in $(license_files "$goroot"); do
    fence "$(basename "$f")" "$f"
  done

  go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}}{{end}}{{end}}' ./cmd/wamux-http \
    | LC_ALL=C sort -u \
    | while read -r path version; do
        dir=$(go list -m -f '{{.Dir}}' "$path@$version")
        files=$(license_files "$dir")
        [ -n "$files" ] || { echo "third-party-licenses: $path has no license file" >&2; exit 1; }
        printf '\n## %s %s\n\nSource: https://proxy.golang.org/%s/@v/%s.zip\n' \
          "$path" "$version" "$(escape "$path")" "$(escape "$version")"
        for f in $files; do
          fence "$(basename "$f")" "$f"
        done
      done

  printf '\n## Embedded in the panel (internal/dashboard/static)\n'
  printf '\nDatastar v1.0.4, https://github.com/starfederation/datastar\n'
  fence datastar.LICENSE.md internal/dashboard/static/datastar.LICENSE.md
  printf '\nIBM Plex Mono and IBM Plex Sans (latin subset, via Fontsource 5.3.0), https://github.com/IBM/plex\n'
  fence OFL.txt internal/dashboard/static/fonts/OFL.txt
} > "$out"
