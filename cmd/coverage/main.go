// Command coverage writes docs/coverage.md: which of WAHA's operations this
// edge implements and which answer 501, read from the routes the server
// actually registers. With -check it fails when the file is out of date.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/LLawli/wamux-http/contract"
	"github.com/LLawli/wamux-http/internal/httpapi"
)

func main() {
	check := flag.Bool("check", false, "fail if the file differs instead of writing it")
	flag.Parse()
	path := flag.Arg(0)
	if path == "" {
		path = "docs/coverage.md"
	}
	want := render()
	if *check {
		got, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(got, want) {
			fmt.Fprintf(os.Stderr, "%s is out of date: run 'go run ./cmd/coverage'\n", path)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(path, want, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func render() []byte {
	s := &httpapi.Server{}
	s.Router()
	missing := map[string]bool{}
	for _, op := range s.Coverage() {
		missing[op] = true
	}
	type tagStat struct {
		name       string
		done, todo []string
	}
	var tags []*tagStat
	byTag := map[string]*tagStat{}
	for _, op := range contract.Operations() {
		name := strings.TrimSpace(strings.TrimLeftFunc(op.Tag, func(r rune) bool { return r > 127 || r == ' ' }))
		t := byTag[name]
		if t == nil {
			t = &tagStat{name: name}
			byTag[name] = t
			tags = append(tags, t)
		}
		line := fmt.Sprintf("`%s %s`", op.Method, op.Path)
		if missing[op.Method+" "+op.Path] {
			t.todo = append(t.todo, line)
		} else {
			t.done = append(t.done, line)
		}
	}
	var b bytes.Buffer
	total, done := len(contract.Operations()), total0(tags, func(t *tagStat) int { return len(t.done) })
	fmt.Fprintf(&b, "# WAHA coverage\n\nGenerated by `go run ./cmd/coverage` from the routes the server registers; CI fails when it is stale.\n\n")
	fmt.Fprintf(&b, "**%d of %d** WAHA operations are implemented. Every other one answers WAHA's `501 Not Implemented`.\n\n", done, total)
	fmt.Fprintf(&b, "| Area | Implemented | 501 |\n|---|---|---|\n")
	for _, t := range tags {
		fmt.Fprintf(&b, "| %s | %d | %d |\n", t.name, len(t.done), len(t.todo))
	}
	for _, t := range tags {
		if len(t.todo) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n## %s: answers 501\n\n", t.name)
		for _, l := range t.todo {
			fmt.Fprintf(&b, "- %s\n", l)
		}
	}
	return b.Bytes()
}

func total0[T any](xs []T, f func(T) int) int {
	n := 0
	for _, x := range xs {
		n += f(x)
	}
	return n
}
